-- ارسال یک اعلان همگانی به همهٔ کاربران (اپ و سایت)
--
-- این فایل را کامل کپی کنید و در Supabase → SQL Editor → New query اجرا کنید.
-- هیچ نسخهٔ جدید اپ لازم نیست؛ از زیرساخت موجود V232/V284 استفاده می‌کند.
--
-- چه کسی پیام را می‌گیرد؟
--   • همهٔ حساب‌های ثبت‌شده: پیام در «مرکز اعلان» (زنگولهٔ داخل اپ و سایت)
--     دیده می‌شود — حتی اگر اعلان دستگاهی را خاموش کرده باشند.
--   • کسانی که اعلان را روشن کرده‌اند (اپ اندروید یا PWA سایت): علاوه بر آن،
--     اعلان روی گوشی/مرورگرشان هم می‌آید.
--
-- ارسال خودکار است: زمان‌بند هر دقیقه صندوق را خالی می‌کند (push_tick).
-- =====================================================================

-- ---------------------------------------------------------------------
-- گام ۱ — فقط متن را این‌جا عوض کنید، بعد کل فایل را Run بزنید
-- ---------------------------------------------------------------------
do $$
declare
  v_title text := 'پیام سازنده';
  v_body  text := 'اولین شارژ تا ۱٬۰۰۰٬۰۰۰ تومان، دوبرابر اعتبار هدیه بگیرید. همین الآن کیف پول خود را شارژ کنید.';
  v_page  text := '';                    -- '' = صفحهٔ اصلی (کیف پول از آن‌جا در دسترس است)
  v_slug  text := 'dev-2x-1405-08-16-b';      -- شناسهٔ یکتای این پیام؛ برای پیام بعدی حتماً عوض کنید
  n int;
begin
  insert into public.push_outbox(user_id, kind, title, body, data, dedupe_key)
  select p.id,
         'announcement',
         left(v_title, 120),
         left(v_body, 400),
         jsonb_build_object('page', v_page),
         'broadcast:' || v_slug || ':' || p.id::text
  from public.profiles p
  on conflict (dedupe_key) do nothing;
  get diagnostics n = row_count;
  raise notice 'پیام برای % کاربر ثبت شد.', n;
end $$;

-- ---------------------------------------------------------------------
-- گام ۲ — بررسی: چند نفر در صف هستند و چند نفر ارسال شده
-- ---------------------------------------------------------------------
select state,
       count(*) as تعداد
from public.push_outbox
where kind = 'announcement'
group by state
order by state;

-- نمونهٔ پیامی که کاربر می‌بیند
select title, body, created_at
from public.push_outbox
where kind = 'announcement'
order by created_at desc
limit 3;

